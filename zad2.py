# Задача 2 — До отрицателното число (25 т.)
# Въвеждат се цели числа, всяко на отделен ред, докато не се въведе отрицателно число. Отрицателното число не е част от редицата.
# а) (6 т.) Прочетете числата с цикъл. Ако първото число е отрицателно, изведете Няма данни.
# б) (6 т.) Изведете сумата на числата.
# в) (7 т.) Изведете колко от числата са двуцифрени.
# г) (6 т.) Изведете средното аритметично на числата, закръглено до 2 знака след десетичната запетая.
# Вход:
# 12
# 5
# 47
# 100
# 8
# -1

# Изход:
# Сума: 171
# Двуцифрени: 2
# Средно: 34.40

suma = 0
br_vsichki = 0
br_dvcif = 0

chislo = int(input("Enter a number: "))

if chislo < 0:
    print("Няма данни")
else:
    while chislo >= 0:
        suma = suma + chislo
        br_vsichki = br_vsichki + 1
        if 10 <= chislo <= 99:
            br_dvcif = br_dvcif + 1
        chislo = int(input())
    sredno = suma / br_vsichki
    print(f"Сума:{suma}")
    print(f"Двуцифрени:{br_dvcif}")
    print(f"Средно: {sredno:.2f}")
