# Задача 3 — Цифрите на числото (25 т.)
# а) (4 т.) Въвежда се цяло число n. Докато n ≤ 0, програмата чете ново число.
# б) (8 т.) Изведете сумата от цифрите на n.
# в) (7 т.) Изведете числото, записано отзад напред (за 1230 това е 321).
# г) (6 т.) Ако числото е равно на обърнатото си, изведете Палиндром, иначе Не е палиндром.
# Вход:
# 12321

# Изход:
# Сума на цифрите: 9
# Обърнато: 12321
# Палиндром

sumcif = 0
obr = 0
pal = -1

n = int(input("Enter a number: "))
while n <= 0:
    n = int(input("Enter a number>0: "))
r = n

while r > 0:
    if r >= 10:
        sumcif += r % 10
        r //= 10
    else:
        sumcif += r
        r //= 10

r = n
while r > 0:
    if r >= 10:
        obr = obr*10 + r%10
        r //= 10
    else:
        obr = obr*10 + r
        r //= 10
print(f"Сума на цифрите: {sumcif}.")
print(f"Обърнато: {obr}.")
if n == obr:
    print("Палиндром")
else: 
    print("Не е палиндром")
